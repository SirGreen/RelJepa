"""Generate paper/tables/primary.tex: the pre-registered primary endpoints E1-E5.

Sources (all written by scripts): results/tables/summary.csv and summary_bootstrap.csv
(scripts/analyze_results.py) for E1-E3, results/tables/info_probes_bootstrap.csv
(scripts/probes/bootstrap_probes.py) for E4-E5. Do not edit the .tex by hand.

Top block: test score per method (mean ± std over 3 fine-tuning seeds for E1-E3; one probe fit per
encoder for E4-E5). Bottom block: 95% paired bootstrap intervals of the primary contrasts; bold
when the interval excludes zero.
The post hoc TVE-1+head control has a dagger, no E1 run ("--") and one contrast row,
RelJEPA+TVE - TVE-1+head, which isolates the learned targets.
Usage: python scripts/tables/make_table_primary.py
"""
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TABLES = os.path.join(ROOT, "results", "tables")
OUT = os.path.join(ROOT, "paper", "tables", "primary.tex")

METHODS = [("scratch", "Scratch"), ("mae", "MFR"), ("tve1", "TVE-1"), ("tve1-empty", "\\tvehead{}$^\\dagger$"),
           ("reljepa", "\\method{}"), ("reljepa-tve", "\\method{}+TVE")]
CONTRASTS = [("reljepa", "tve1", "\\method{} $-$ TVE-1"), ("reljepa-tve", "tve1", "\\method{}+TVE $-$ TVE-1"),
             ("reljepa-tve", "reljepa", "\\method{}+TVE $-$ \\method{}"),
             ("reljepa-tve", "tve1-empty", "\\method{}+TVE $-$ \\tvehead{}$^\\dagger$")]
MISSING = "--"   # a method or contrast without a run for this endpoint (TVE-1+head has no E1)
# (id, header, source, stage-or-probe, task, scale, decimals)
ENDPOINTS = [
    ("E2", "Churn AUROC $\\uparrow$", "node", "probe", "user-churn", 100, 2),
    ("E3", "Sales MAE $\\downarrow$", "node", "probe", "item-sales", 1, 4),
    ("E1", "MAP@12 $\\uparrow$", "node", "rec-low", "user-item-purchase", 100, 3),
    ("E4", "Recall@12 $\\uparrow$", "info", "item_recall12", None, 100, 2),
    ("E5", "Spend $R^2$ $\\uparrow$", "info", "spend_r2", None, 100, 2),
]


def _rows(src, key, task, summary, boot, info):
    """Per-method score cells and the bootstrap table rows for one endpoint."""
    if src == "node":
        s = summary[(summary["stage"] == key) & (summary["task"] == task)].set_index("method")
        b = boot[(boot["stage"] == key) & (boot["task"] == task)].set_index("method")
        return s, b
    b = info[info["probe"] == key].set_index("method")
    return None, b


def _signed(x, dec):
    return f"{x:+.{dec}f}".replace("+", "$+$").replace("-", "$-$")


def main():
    summary = pd.read_csv(os.path.join(TABLES, "summary.csv"))
    boot = pd.read_csv(os.path.join(TABLES, "summary_bootstrap.csv"))
    info = pd.read_csv(os.path.join(TABLES, "info_probes_bootstrap.csv"))
    cols = [(e, *_rows(src, key, task, summary, boot, info), scale, dec) for e, _, src, key, task, scale, dec in ENDPOINTS]

    lines = [
        "% Generated by scripts/tables/make_table_primary.py. Do not edit.",
        "\\begin{table}[t]",
        "\\caption{Pre-registered primary endpoints on H\\&M (test). E2, E3: linear probes on the frozen "
        "encoder, full-data churn (AUROC ${\\times}100$) and article sales (MAE). E1: recommendation with 10\\% of training customers "
        "(MAP@12 ${\\times}100$). E4, E5: information probes on frozen customer embeddings (Recall@12 of "
        "next-week articles and mean $R^2$ of next-week spend per product group, ${\\times}100$). E1--E3: "
        "mean $\\pm$ std over 3 fine-tuning seeds; E4, E5: one probe fit per encoder. Bottom: 95\\% paired "
        "bootstrap intervals (2{,}000 resamples of test examples); bold intervals exclude zero. For MAE a "
        "negative difference is an improvement. $^\\dagger$Post hoc control, TVE-1 with the empty-window "
        "head: not pre-registered, no E1 run.}",
        "\\label{tab:primary}",
        "\\centering\\scriptsize\\setlength{\\tabcolsep}{1.5pt}",
        "\\begin{tabular}{@{}l" + "c" * len(cols) + "@{}}",
        "\\toprule",
        " & \\multicolumn{2}{c}{H1: linear probe} & \\multicolumn{3}{c}{H2: information beyond statistics} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(l){4-6}",
        " & " + " & ".join(e for e, *_ in ENDPOINTS) + " \\\\",
        " & " + " & ".join(h for _, h, *_ in ENDPOINTS) + " \\\\",
        "\\midrule",
    ]
    for key, label in METHODS:
        cells = []
        for _, s, b, scale, dec in cols:
            if s is not None:
                if key not in s.index:
                    cells.append(MISSING)
                    continue
                r = s.loc[key]
                cells.append(f"{r.test_mean * scale:.{dec}f} $\\pm$ {r.test_std * scale:.{dec}f}")
            else:
                cells.append(f"{b.loc[key, 'value'] * scale:.{dec}f}")
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines.append("\\midrule")
    for a, ref, label in CONTRASTS:
        cells = []
        for _, _, b, scale, dec in cols:
            low = b.loc[a].get(f"diff_vs_{ref}_low")
            if low is None or pd.isna(low):
                cells.append(MISSING)
                continue
            lo, hi = low * scale, b.loc[a, f"diff_vs_{ref}_high"] * scale
            cell = f"[{_signed(lo, dec)}, {_signed(hi, dec)}]"
            cells.append(f"\\textbf{{{cell}}}" if lo > 0 or hi < 0 else cell)
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

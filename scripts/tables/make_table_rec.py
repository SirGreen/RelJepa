"""Generate paper/tables/rec.tex (recommendation) from results/raw/finetune.csv and
results/tables/summary_bootstrap.csv. Do not edit the .tex by hand.

Recommendation runs (ft-rec-{low,1pct,0p1pct}-<method>: 10%, 1% and 0.1% of training customers)
have no LR sweep. One row per method: test MAP@12 in every setting, and
precision@12 and recall@12 in the 10% setting (x100, 3 decimals), mean ± std over seeds at each seed's
best-validation epoch. Last row: 95% paired bootstrap interval of RelJEPA - TVE-1 on MAP@12.
"""
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, "results", "raw", "finetune.csv")
BOOT = os.path.join(ROOT, "results", "tables", "summary_bootstrap.csv")
OUT = os.path.join(ROOT, "paper", "tables", "rec.tex")
METHODS = [("scratch", "Scratch"), ("mae", "MFR"), ("tve1", "TVE-1"), ("reljepa", "\\method{}"),
           ("reljepa-tve", "\\method{}+TVE")]
METRICS = [("link_prediction_map", "MAP@12"), ("link_prediction_precision", "Prec@12"),
           ("link_prediction_recall", "Rec@12")]
SETTINGS = [("rec-low", "ft-rec-low-", "10\\%"), ("rec-1pct", "ft-rec-1pct-", "1\\%"),
            ("rec-0p1pct", "ft-rec-0p1pct-", "0.1\\%")]


def _cell(df, name, metric):
    v = df[(df["name"] == name) & (df["split"] == "test") & (df["metric"] == metric)]["value"] * 100
    if v.empty:
        return "--"
    return f"{v.mean():.3f} $\\pm$ {v.std(ddof=1):.3f}" if len(v) > 1 else f"{v.mean():.3f}"


def _signed(x):
    return f"{x:+.3f}".replace("+", "$+$").replace("-", "$-$")


def main():
    df = pd.read_csv(CSV)
    boot = pd.read_csv(BOOT)
    header = [f"MAP@12, {pct}" for _, _, pct in SETTINGS] + [f"{h}, 10\\%" for _, h in METRICS[1:]]
    rows = []
    for key, label in METHODS:
        cells = [_cell(df, prefix + key, METRICS[0][0]) for _, prefix, _ in SETTINGS]
        cells += [_cell(df, SETTINGS[0][1] + key, metric) for metric, _ in METRICS[1:]]
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    diff = []
    for stage, _, _ in SETTINGS:
        r = boot[(boot["stage"] == stage) & (boot["method"] == "reljepa")]
        if r.empty:
            diff.append("--")
            continue
        lo, hi = r.iloc[0]["diff_vs_tve1_low"] * 100, r.iloc[0]["diff_vs_tve1_high"] * 100
        cell = f"[{_signed(lo)}, {_signed(hi)}]"
        diff.append(f"\\textbf{{{cell}}}" if lo > 0 or hi < 0 else cell)
    rows += ["\\midrule",
             "\\method{} $-$ TVE-1 & " + " & ".join(diff + [""] * (len(METRICS) - 1)) + " \\\\"]
    lines = [
        "% Generated by scripts/tables/make_table_rec.py. Do not edit.",
        "\\begin{table}[t]",
        "\\caption{Next-week article recommendation on H\\&M with an ID-GNN head, trained on 10\\%, 1\\% "
        "or 0.1\\% of the training customers: test metrics (${\\times}100$, $\\uparrow$) at the best "
        "validation epoch, mean $\\pm$ std over 3 seeds, 67{,}144 test customers. Prec@12 and Rec@12: "
        "precision and recall of the 12 highest-ranked articles. Last row: 95\\% paired "
        "bootstrap interval over test customers of the MAP@12 difference; bold if it excludes zero.}",
        "\\label{tab:rec}",
        "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}l" + "c" * len(header) + "@{}}",
        "\\toprule",
        "Method & " + " & ".join(header) + " \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(METHODS)} methods)")


if __name__ == "__main__":
    main()

"""Generate paper/tables/node_tasks.tex (secondary entity tasks) from results/tables/summary.csv and
summary_bootstrap.csv (written by scripts/analyze_results.py). Do not edit the .tex by hand.

One row per (setting, task), one column per method, plus the 95% paired bootstrap interval over
test examples of RelJEPA - TVE-1 (the primary contrast). Formatting: AUROC
x100 with 2 decimals; MAE with 3 decimals for top-200 sales and 4 for full-data sales; mean ± std
over seeds. A cell is bold only if it is the best mean AND the paired bootstrap interval of its
difference to every other method excludes 0 (stated in the caption).
"""
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SUMMARY = os.path.join(ROOT, "results", "tables", "summary.csv")
BOOT = os.path.join(ROOT, "results", "tables", "summary_bootstrap.csv")
OUT = os.path.join(ROOT, "paper", "tables", "node_tasks.tex")

METHODS = [("scratch", "Scratch"), ("mae", "MFR"), ("tve1", "TVE-1"), ("reljepa", "\\method{}"),
           ("reljepa-tve", "\\method{}+TVE")]
COLUMNS = [  # (stage, task, header, metric, scale, decimals, higher_is_better)
    ("limited", "user-churn-top50-spending", "Churn top-50", "roc_auc", 100, 2, True),
    ("limited", "user-churn-top100-spending", "Churn top-100", "roc_auc", 100, 2, True),
    ("limited", "item-sales-top200-spending", "Sales top-200", "mae", 1, 3, False),
    ("probe", "user-churn-top50-spending", "Churn top-50", "roc_auc", 100, 2, True),
    ("probe", "user-churn-top100-spending", "Churn top-100", "roc_auc", 100, 2, True),
    ("probe", "item-sales-top200-spending", "Sales top-200", "mae", 1, 3, False),
    ("full", "user-churn", "Churn", "roc_auc", 100, 2, True),
    ("full", "item-sales", "Sales", "mae", 1, 4, False),
]
NAMES = {"limited": "Fine-tuning, limited labels", "probe": "Linear probe, limited labels",
         "full": "Fine-tuning, full data"}


def _separated(b, stage, task, key, others, hib):
    """True if every paired interval of `key` against the other methods excludes 0 in its favour."""
    bb = b[(b["stage"] == stage) & (b["task"] == task) & (b["method"] == key)]
    if not len(bb):
        return False
    res = []
    for other in others:
        lo = bb.iloc[0].get(f"diff_vs_{other}_low", np.nan)
        hi = bb.iloc[0].get(f"diff_vs_{other}_high", np.nan)
        res.append(not np.isnan(lo) and (lo > 0 if hib else hi < 0))
    return bool(res) and all(res)


def _signed(x, dec):
    return f"{x:+.{dec}f}".replace("+", "$+$").replace("-", "$-$")


def _stack(label):
    """Two-line header for labels with a "+" or " $-$ " (keeps the columns narrow)."""
    for sep in (" $-$ ", "+"):
        if sep in label:
            head, tail = label.split(sep, 1)
            tail = sep.lstrip() + tail   # "$-$ TVE-1" or "+TVE"
            return f"\\begin{{tabular}}[b]{{@{{}}c@{{}}}}{head}\\\\{tail}\\end{{tabular}}"
    return label


def main():
    s = pd.read_csv(SUMMARY)
    b = pd.read_csv(BOOT) if os.path.exists(BOOT) else pd.DataFrame()
    cols = [c for c in COLUMNS if ((s["stage"] == c[0]) & (s["task"] == c[1])).any()]
    width = len(METHODS) + 2
    lines = [
        "% Generated by scripts/tables/make_table_node.py. Do not edit.",
        "\\begin{table}[t]",
        "\\caption{Entity tasks on H\\&M (secondary endpoints): test AUROC (${\\times}100$, $\\uparrow$) "
        "or MAE ($\\downarrow$), mean $\\pm$ std over 3 seeds at the learning rate selected on validation. "
        "Last column: 95\\% paired bootstrap interval over test examples of \\method{} $-$ TVE-1. Bold: "
        "best mean whose paired interval against every other method excludes zero. Limited-label test "
        "sets have 50, 100 and 200 examples.}",
        "\\label{tab:node}",
        "\\centering\\scriptsize\\setlength{\\tabcolsep}{1.5pt}",
        "\\begin{tabular}{@{}l" + "c" * len(METHODS) + "c@{}}",
        "\\toprule",
        "Task & " + " & ".join(_stack(label) for _, label in METHODS)
        + " & " + _stack("\\method{} $-$ TVE-1") + " \\\\",
    ]
    stage_seen = None
    for stage, task, header, metric, scale, dec, hib in cols:
        if stage != stage_seen:
            lines += ["\\midrule", f"\\multicolumn{{{width}}}{{@{{}}l}}{{\\emph{{{NAMES[stage]}}}}} \\\\"]
            stage_seen = stage
        group = s[(s["stage"] == stage) & (s["task"] == task)].set_index("method")
        best = group["test_mean"].max() if hib else group["test_mean"].min()
        cells = []
        for key, _ in METHODS:
            if key not in group.index:
                cells.append("--")
                continue
            r = group.loc[key]
            cell = f"{r.test_mean * scale:.{dec}f}\\,$\\pm$\\,{r.test_std * scale:.{dec}f}"   # thin spaces: fits the text width
            others = [m for m in group.index if m != key]
            if np.isclose(r.test_mean, best) and len(b) and _separated(b, stage, task, key, others, hib):
                cell = f"\\textbf{{{cell}}}"
            cells.append(cell)
        bb = b[(b["stage"] == stage) & (b["task"] == task) & (b["method"] == "reljepa")] if len(b) else b
        if len(bb) and not np.isnan(bb.iloc[0].get("diff_vs_tve1_low", np.nan)):
            lo, hi = bb.iloc[0]["diff_vs_tve1_low"] * scale, bb.iloc[0]["diff_vs_tve1_high"] * scale
            cells.append(f"[{_signed(lo, dec)}, {_signed(hi, dec)}]")
        else:
            cells.append("--")
        lines.append(f"{header} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

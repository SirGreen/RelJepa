"""Generate paper/tables/tasks.tex (Table 1) from results/raw/task_stats.csv."""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "results", "raw", "task_stats.csv")
OUT = os.path.join(ROOT, "paper", "tables", "tasks.tex")

TASKS = [  # (task id, display name, type, metric, root)
    ("user-churn", "Churn", "Classification", "AUROC $\\uparrow$", "Customer"),
    ("user-churn-top50-spending", "Churn, top-50 spenders", "Classification", "AUROC $\\uparrow$", "Customer"),
    ("user-churn-top100-spending", "Churn, top-100 spenders", "Classification", "AUROC $\\uparrow$", "Customer"),
    ("item-sales", "Sales", "Regression", "MAE $\\downarrow$", "Article"),
    ("item-sales-top200-spending", "Sales, top-200 articles", "Regression", "MAE $\\downarrow$", "Article"),
    ("user-item-purchase", "Next-week purchases", "Recommendation", "MAP@12 $\\uparrow$", "Customer"),
]

rows = {}
with open(SRC) as f:
    for r in csv.DictReader(f):
        rows[(r["task"], r["split"])] = int(r["rows"])


def fmt(n):
    return f"{n:,}".replace(",", "{,}")


lines = [
    "% Generated by scripts/tables/make_table_tasks.py from results/raw/task_stats.csv. Do not edit.",
    "\\begin{table}[t]",
    "\\caption{Tasks on the RelBench H\\&M database ($\\Delta = 7$ days). Rows are (entity, cutoff) "
    "examples; training cutoffs are 52 weekly dates from 9 Sep 2019 to 31 Aug 2020, and validation and "
    "test use one cutoff each (7 and 14 Sep 2020). The low-label recommendation setting keeps 10\\% of "
    "the training customers.}",
    "\\label{tab:tasks}",
    "\\centering\\small",
    "\\begin{tabular}{@{}llllrrr@{}}",
    "\\toprule",
    "Task & Root & Type & Metric & Train & Val & Test \\\\",
    "\\midrule",
]
for task, name, typ, metric, root in TASKS:
    tr, va, te = (rows[(task, s)] for s in ("train", "val", "test"))
    lines.append(f"{name} & {root} & {typ} & {metric} & {fmt(tr)} & {fmt(va)} & {fmt(te)} \\\\")
lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"wrote {OUT}")
